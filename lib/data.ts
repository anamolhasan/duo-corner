export const parseImages = (input: unknown): string[] => {
  if (Array.isArray(input)) {
    return input
      .map((img: unknown) => {
        const clean = String(img).trim();
        if (!clean) return "";
        return /^https?:\/\//i.test(clean)
          ? clean
          : clean.startsWith("/")
            ? clean
            : "/" + clean;
      })
      .filter(Boolean);
  }
  if (typeof input === "string" && input.trim() !== "") {
    return input
      .split(",")
      .map((img) => {
        const clean = img.trim();
        if (!clean) return "";
        return /^https?:\/\//i.test(clean)
          ? clean
          : clean.startsWith("/")
            ? clean
            : "/" + clean;
      })
      .filter(Boolean);
  }
  return ["/parl.jpg"];
};

export async function getProducts(): Promise<Product[]> {
  try {
    const res = await fetch("/api/products", { cache: "no-store" });
    const data = await res.json();

    if (Array.isArray(data) && data.length > 0) {
      return data.map((rawItem: unknown, index: number) => {
        const item: Record<string, unknown> =
          rawItem !== null && typeof rawItem === "object"
            ? (rawItem as Record<string, unknown>)
            : {};
        const prodName = String(
          item["Product Name"] || item.productName || item.Name || "Product",
        );
        const offerPrice = Number(item["Offer Price"] || item.price || 799);
        const regularPrice = Number(
          item["Regular Price"] || item.regularPrice || 999,
        );
        const category = String(
          item["Category"] || item.category || "Couple Item",
        );
        const description = String(
          item["Description"] ||
            item.description ||
            "এক্সক্লুসিভ কাপল প্রোডাক্ট।",
        );

        const img1 = item["Image URL1"] || item.imageUrl1;
        const img2 = item["Image URL2"] || item.imageUrl2;
        const img3 = item["Image URL3"] || item.imageUrl3;
        const img4 = item["Image URL4"] || item.imageUrl4;

        const images = parseImages([img1, img2, img3, img4]);

        return {
          id: Number(item.id) || index + 1,
          name: prodName,
          shortName: prodName,
          basePrice: offerPrice,
          regularPrice: regularPrice,
          originalPrice: `৳${regularPrice}`,
          images: images.length > 0 ? images : ["/parl.jpg"],
          videoUrl: String(item["Video URL"] || item.videoUrl || "/video.mp4"),
          badge: "🔥 Hot Deal",
          saving: "Save ৳200",
          description: description,
          attributes: [
            { label: "Product Type", value: category },
            { label: "Stock", value: String(item["Stock"] || "100") },
          ],
        };
      });
    }
    return [];
  } catch (error) {
    console.error("Error fetching products:", error);
    return [];
  }
}

